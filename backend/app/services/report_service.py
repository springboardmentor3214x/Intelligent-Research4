import io
from datetime import datetime
from typing import Any
import xml.sax.saxutils as saxutils

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    KeepTogether,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from backend.app.schemas.report import ReportRequest

try:
    import openpyxl
    from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
    from openpyxl.utils import get_column_letter
    OPENPYXL_AVAILABLE = True
except ImportError:
    OPENPYXL_AVAILABLE = False


REPORT_TITLES = {
    "funding": "Funding Intelligence Report",
    "patent": "Patent Landscape Intelligence Report",
    "research_trend": "Research Trends & Literature Analysis Report",
    "innovation_intelligence": "Innovation Intelligence & Scoring Report",
    "commercialization": "Commercialization Opportunities Report",
    "unified_intelligence": "Unified Research & Innovation Intelligence Report",
}


def _safe_text(value: Any) -> str:
    if value is None:
        return "N/A"
    return saxutils.escape(str(value))


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.HexColor("#587083"))
    canvas.drawString(
        20 * mm,
        12 * mm,
        "Research Funding & Innovation Intelligence Platform | Confidential",
    )
    page_text = f"Page {doc.page}"
    canvas.drawRightString(195 * mm, 12 * mm, page_text)
    canvas.setStrokeColor(colors.HexColor("#dce7ee"))
    canvas.setLineWidth(0.5)
    canvas.line(20 * mm, 16 * mm, 195 * mm, 16 * mm)
    canvas.restoreState()


def generate_pdf_report(report: ReportRequest) -> bytes:
    """Generate a structured, professional PDF report from ReportRequest."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=20 * mm,
        rightMargin=20 * mm,
        topMargin=20 * mm,
        bottomMargin=22 * mm,
    )

    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=22,
        leading=26,
        textColor=colors.HexColor("#073b5c"),
        spaceAfter=6,
    )

    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#079b91"),
        spaceAfter=15,
    )

    heading_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#073b5c"),
        spaceBefore=14,
        spaceAfter=8,
        keepWithNext=True,
    )

    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor("#173a53"),
        spaceAfter=8,
    )

    small_style = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#173a53"),
    )

    story = []

    # Title & Metadata
    report_type_name = REPORT_TITLES.get(report.report_type, "Intelligence Report")
    generated_at = getattr(report, "generated_at", None) or datetime.utcnow()

    story.append(Spacer(1, 10 * mm))
    story.append(Paragraph(_safe_text(report.title), title_style))
    story.append(Paragraph(_safe_text(report_type_name), subtitle_style))

    metadata = [
        ["Report Type", report_type_name],
        ["Generated Date", generated_at.strftime("%Y-%m-%d %H:%M UTC")],
        ["Generated By", report.generated_by or "Authenticated User"],
    ]
    if report.organization:
        metadata.append(["Organization", report.organization])

    meta_table = Table(metadata, colWidths=[40 * mm, 120 * mm])
    meta_table.setStyle(
        TableStyle([
            ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#dce7ee")),
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f4f8fc")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ])
    )
    story.append(meta_table)
    story.append(Spacer(1, 6 * mm))

    # Executive Summary
    if report.executive_summary:
        story.append(Paragraph("Executive Summary", heading_style))
        story.append(Paragraph(_safe_text(report.executive_summary), body_style))

    # Applied Filters
    if report.filters:
        story.append(Paragraph("Applied Scope & Filters", heading_style))
        filter_rows = [["Filter Criteria", "Specified Value"]]
        for k, v in report.filters.items():
            filter_rows.append([k.replace("_", " ").title(), _safe_text(v)])
        
        f_table = Table(filter_rows, colWidths=[55 * mm, 105 * mm])
        f_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e9f7f6")),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#dce7ee")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ])
        )
        story.append(f_table)
        story.append(Spacer(1, 4 * mm))

    # Sections
    for sec in report.sections:
        story.append(Paragraph(_safe_text(sec.title), heading_style))
        for p in sec.paragraphs:
            story.append(Paragraph(_safe_text(p), body_style))

        if sec.table_headers and sec.table_rows:
            table_data = [
                [Paragraph(f"<b>{_safe_text(h)}</b>", small_style) for h in sec.table_headers]
            ]
            for row in sec.table_rows:
                table_data.append([Paragraph(_safe_text(c), small_style) for c in row])

            num_cols = len(sec.table_headers)
            avail_width = 160 * mm
            col_widths = [avail_width / num_cols] * num_cols if num_cols else None

            rep_table = Table(table_data, colWidths=col_widths, repeatRows=1)
            rep_table.setStyle(
                TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f0f4f8")),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#dce7ee")),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ("LEFTPADDING", (0, 0), (-1, -1), 4),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ])
            )
            story.append(KeepTogether(rep_table))
            story.append(Spacer(1, 5 * mm))

    # Recommendations
    if report.recommendations:
        story.append(Paragraph("Strategic Recommendations", heading_style))
        for idx, rec in enumerate(report.recommendations, start=1):
            story.append(Paragraph(f"<b>{idx}.</b> {_safe_text(rec)}", body_style))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


def generate_excel_report(report: ReportRequest) -> bytes:
    """Generate a clean, structured multi-column XLSX workbook from ReportRequest."""
    if not OPENPYXL_AVAILABLE:
        raise RuntimeError("openpyxl is not installed on the system.")

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Intelligence Report"
    ws.views.sheetView[0].showGridLines = True

    # Styling definitions
    brand_header_fill = PatternFill(start_color="073B5C", end_color="073B5C", fill_type="solid")
    brand_header_font = Font(name="Arial", size=14, bold=True, color="FFFFFF")
    
    sec_fill = PatternFill(start_color="E9F7F6", end_color="E9F7F6", fill_type="solid")
    sec_font = Font(name="Arial", size=11, bold=True, color="073B5C")
    
    tbl_header_fill = PatternFill(start_color="DCE7EE", end_color="DCE7EE", fill_type="solid")
    tbl_header_font = Font(name="Arial", size=10, bold=True, color="073B5C")
    
    meta_key_font = Font(name="Arial", size=10, bold=True, color="587083")
    regular_font = Font(name="Arial", size=10, color="173A53")
    
    thin_border = Border(
        left=Side(style="thin", color="DCE7EE"),
        right=Side(style="thin", color="DCE7EE"),
        top=Side(style="thin", color="DCE7EE"),
        bottom=Side(style="thin", color="DCE7EE"),
    )

    row = 1
    # Title Banner
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=6)
    cell = ws.cell(row=row, column=1, value=report.title)
    cell.fill = brand_header_fill
    cell.font = brand_header_font
    cell.alignment = Alignment(horizontal="left", vertical="center")
    ws.row_dimensions[row].height = 30
    row += 2

    # Metadata Block
    ws.cell(row=row, column=1, value="Report Type:").font = meta_key_font
    ws.cell(row=row, column=2, value=REPORT_TITLES.get(report.report_type, report.report_type)).font = regular_font
    row += 1

    generated_at = getattr(report, "generated_at", None) or datetime.utcnow()
    ws.cell(row=row, column=1, value="Generated At:").font = meta_key_font
    ws.cell(row=row, column=2, value=generated_at.strftime("%Y-%m-%d %H:%M UTC")).font = regular_font
    row += 1

    if report.generated_by:
        ws.cell(row=row, column=1, value="Generated By:").font = meta_key_font
        ws.cell(row=row, column=2, value=report.generated_by).font = regular_font
        row += 1

    if report.organization:
        ws.cell(row=row, column=1, value="Organization:").font = meta_key_font
        ws.cell(row=row, column=2, value=report.organization).font = regular_font
        row += 1

    if report.filters:
        row += 1
        ws.cell(row=row, column=1, value="Applied Scope / Filters").font = sec_font
        row += 1
        for k, v in report.filters.items():
            ws.cell(row=row, column=1, value=k.replace("_", " ").title()).font = meta_key_font
            ws.cell(row=row, column=2, value=str(v)).font = regular_font
            row += 1

    if report.executive_summary:
        row += 1
        ws.cell(row=row, column=1, value="Executive Summary").font = sec_font
        row += 1
        ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=6)
        c = ws.cell(row=row, column=1, value=report.executive_summary)
        c.font = regular_font
        c.alignment = Alignment(wrap_text=True)
        ws.row_dimensions[row].height = 40
        row += 1

    # Sections & Tables
    for sec in report.sections:
        row += 1
        ws.cell(row=row, column=1, value=sec.title).font = sec_font
        row += 1
        for p in sec.paragraphs:
            ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=6)
            c = ws.cell(row=row, column=1, value=p)
            c.font = regular_font
            c.alignment = Alignment(wrap_text=True)
            row += 1

        if sec.table_headers and sec.table_rows:
            # Write Table Header
            for col_idx, h in enumerate(sec.table_headers, start=1):
                c = ws.cell(row=row, column=col_idx, value=h)
                c.fill = tbl_header_fill
                c.font = tbl_header_font
                c.border = thin_border
                c.alignment = Alignment(horizontal="center", vertical="center")
            ws.row_dimensions[row].height = 20
            row += 1

            # Write Table Rows
            for r_data in sec.table_rows:
                for col_idx, val in enumerate(r_data, start=1):
                    c = ws.cell(row=row, column=col_idx, value=val)
                    c.font = regular_font
                    c.border = thin_border
                    c.alignment = Alignment(vertical="center")
                row += 1

    # Recommendations
    if report.recommendations:
        row += 1
        ws.cell(row=row, column=1, value="Recommendations").font = sec_font
        row += 1
        for idx, rec in enumerate(report.recommendations, start=1):
            ws.cell(row=row, column=1, value=f"{idx}.").font = meta_key_font
            ws.merge_cells(start_row=row, start_column=2, end_row=row, end_column=6)
            c = ws.cell(row=row, column=2, value=rec)
            c.font = regular_font
            c.alignment = Alignment(wrap_text=True)
            row += 1

    # Auto-adjust column widths
    for col in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell_item in col:
            val_str = str(cell_item.value or "")
            if cell_item.coordinate not in ws.merged_cells:
                max_len = max(max_len, len(val_str))
        ws.column_dimensions[col_letter].width = max(max_len + 3, 14)

    output = io.BytesIO()
    wb.save(output)
    return output.getvalue()